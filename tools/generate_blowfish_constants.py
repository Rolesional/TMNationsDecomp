#!/usr/bin/env python3
"""Convert the standard Blowfish pi constants from GBX.NET.Crypto to C++."""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import re


EXPECTED_SHA256 = "ddc8f2e4db15022e93941ef9c998d35d3274105d837b693b6931f9630f8c2698"


def emit_array(name: str, values: list[str]) -> str:
    lines = [f"constexpr std::array<std::uint32_t, {len(values)}> {name}{{"]
    for index in range(0, len(values), 6):
        row = ", ".join(value.lower() + "U" for value in values[index : index + 6])
        lines.append(f"    {row},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()

    raw = args.source.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(f"unexpected Blowfish.cs SHA-256: {digest}")

    source = raw.decode("utf-8-sig")
    start = source.index("private readonly uint[] _p")
    values = re.findall(r"0x[0-9A-Fa-f]{8}", source[start:])
    if len(values) != 18 + 1024:
        raise SystemExit(f"expected 1042 constants, found {len(values)}")

    text = "\n".join(
        [
            "// Generated by tools/generate_blowfish_constants.py.",
            "// Standard Blowfish pi constants cross-checked against GBX.NET.Crypto",
            "// commit a83e1ef612e4ad3aa46dd566dfa82265df90442d (MIT).",
            emit_array("kInitialP", values[:18]),
            "",
            emit_array("kInitialS", values[18:]),
            "",
        ]
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()

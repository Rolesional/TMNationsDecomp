#!/usr/bin/env python3
"""Generate the portable GameBox class table from Ghidra's recovered registry."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()

    rows: list[tuple[int, int, str]] = []
    with arguments.input.open(newline="", encoding="utf-8-sig") as stream:
        for row in csv.DictReader(stream):
            rows.append(
                (
                    int(row["classId"], 16),
                    int(row["parentClassId"], 16),
                    row["className"],
                )
            )

    rows.sort()
    ids = [class_id for class_id, _, _ in rows]
    names = [name for _, _, name in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("class registry contains duplicate IDs")
    if len(names) != len(set(names)):
        raise ValueError("class registry contains duplicate names")

    lines = [
        "// Generated by tools/generate_class_registry.py.",
        "// Source: TmForever.exe SHA-256",
        "// 808bf7fed8d74e54950129bb47c6f0a65a25c05415d49e280760db68527fc26f",
    ]
    lines.extend(
        f"    ClassInfo{{0x{class_id:08X}U, 0x{parent_class_id:08X}U, {json.dumps(name)}}},"
        for class_id, parent_class_id, name in rows
    )
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
